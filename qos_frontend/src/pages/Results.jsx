import React, { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import EnergyChart from "../charts/EnergyChart";
import LatencyChart from "../charts/LatencyChart";
import {
  Share2,
  Printer,
  CheckCircle2,
  History,
  Trash2,
  BarChart3,
  Play
} from "lucide-react";
import {
  LineChart,
  Line,
  XAxis,
  YAxis,
  Tooltip,
  Legend,
  ResponsiveContainer,
  CartesianGrid,
} from "recharts";
import { fetchHistory, deleteRun } from "../services/api";

const Results = () => {
  const [result, setResult] = useState(null);
  const [history, setHistory] = useState([]);
  const navigate = useNavigate();

  useEffect(() => {
    const stored = localStorage.getItem("simulationResult");
    if (stored) {
      setResult(JSON.parse(stored));
    }
    loadHistory();
  }, []);

  const loadHistory = async () => {
    const data = await fetchHistory();
    // History comes newest-first; reverse so chart reads oldest→newest
    setHistory([...data].reverse());
    // Auto-fallback: if no simulation has been run in this session yet, populate from latest historical run
    if (!localStorage.getItem("simulationResult") && data && data.length > 0) {
      const latest = data[0];
      setResult({
        ...latest,
        fog_nodes: latest.fog_nodes,
        iot_tasks: latest.iot_tasks,
        cpu_limit: latest.cpu_limit,
        algorithm: latest.algorithm,
      });
    }
  };

  const handleDelete = async (id) => {
    await deleteRun(id);
    loadHistory();
  };

  // ── Share ──────────────────────────────────────────────────────────────────
  const handleShare = async () => {
    if (!result) return;
    const text = `
🔹 EcoFog AI Simulation Analytics Result

Algorithm: ${result.algorithm || "QoS Aware Heuristic"}
Fog Energy: ${result.fog_energy} kWh
Cloud Energy: ${result.cloud_energy} kWh
Energy Saved: ${result.energy_saved_percent}%
QoS Satisfaction: ${result.qos_satisfaction}%
Throughput: ${result.throughput}
Latency: ${result.latency_ms} ms

Generated from EcoFog AI Optimization System`;
    try {
      if (navigator.share) {
        await navigator.share({ title: "Fog Scheduling Result", text });
      } else {
        await navigator.clipboard.writeText(text);
        alert("Result summary copied to clipboard!");
      }
    } catch {}
  };

  // ── Print ──────────────────────────────────────────────────────────────────
  const handlePrint = () => {
    if (!result) return;
    const printContent = `
      <html>
        <head>
          <title>EcoFog AI Simulation Report</title>
          <style>body{font-family:Arial,sans-serif;padding:40px;color:#0f172a} h1{color:#4f46e5} .box{margin:15px 0;font-size:18px} .highlight{font-weight:bold;color:#4f46e5}</style>
        </head>
        <body>
          <h1>EcoFog AI Resource Allocation Report</h1>
          <p>Evaluation of IEERA-Fog Scheduling Engine</p>
          <hr/>
          <div class="box">Algorithm: <span class="highlight">${result.algorithm || "QoS Aware Heuristic"}</span></div>
          <div class="box">Fog Energy: <span class="highlight">${result.fog_energy} kWh</span></div>
          <div class="box">Cloud Energy: <span class="highlight">${result.cloud_energy} kWh</span></div>
          <div class="box">Energy Saved: <span class="highlight">${result.energy_saved_percent}%</span></div>
          <div class="box">QoS Satisfaction: <span class="highlight">${result.qos_satisfaction}%</span></div>
          <div class="box">Throughput: <span class="highlight">${result.throughput}</span></div>
          <div class="box">Latency: <span class="highlight">${result.latency_ms} ms</span></div>
          <hr/>
          <p>Generated by EcoFog AI System</p>
        </body>
      </html>`;
    const w = window.open("", "_blank");
    w.document.write(printContent);
    w.document.close();
    w.print();
  };

  if (!result) {
    return (
      <div className="glass-card" style={{ maxWidth: "550px", margin: "4rem auto", textAlign: "center", padding: "3rem" }}>
        <BarChart3 size={48} color="var(--primary)" style={{ marginBottom: "1rem" }} />
        <h2>No Simulation Active Yet</h2>
        <p style={{ color: "var(--text-muted)", margin: "1rem 0 1.5rem" }}>
          Configure fog environment parameters and evaluate the IEERA-Fog algorithm.
        </p>
        <button className="btn btn-primary" onClick={() => navigate("/simulate")} style={{ display: "inline-flex", alignItems: "center", gap: "0.5rem" }}>
          <Play size={16} /> Launch New Simulation
        </button>
      </div>
    );
  }

  // Prepare history chart data
  const historyChartData = history.map((run) => ({
    name: `#${run.id}`,
    "QoS (%)": run.qos_satisfaction,
    "Fog Energy": run.fog_energy,
    Throughput: run.throughput,
    "Latency (ms)": run.latency_ms,
    algorithm: run.algorithm,
  }));

  return (
    <div className="animate-fade-in">
      {/* Header */}
      <header style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "2rem", flexWrap: "wrap", gap: "1rem" }}>
        <div>
          <h1>Performance Analytics</h1>
          <p style={{ color: "var(--text-muted)" }}>
            Fog node telemetry and algorithmic comparison ({result.algorithm || "Heuristic"}).
          </p>
        </div>
        <div style={{ display: "flex", gap: "0.75rem" }}>
          <button className="btn" onClick={handleShare}>
            <Share2 size={16} /> Share
          </button>
          <button className="btn btn-primary" onClick={handlePrint}>
            <Printer size={16} /> Print Report
          </button>
          <button className="btn" onClick={() => navigate("/simulate")}>
            <Play size={16} /> New Run
          </button>
        </div>
      </header>

      {/* Current Run Charts */}
      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "1.5rem" }}>
        <div className="card">
          <h3 style={{ marginBottom: "1rem" }}>Energy Consumption (Fog vs Cloud)</h3>
          <EnergyChart result={result} />
        </div>
        <div className="card">
          <LatencyChart result={{ ...result, iot_tasks: result.iot_tasks || 100, fog_nodes: result.fog_nodes || 10, algorithm: result.algorithm }} />
        </div>
      </div>

      {/* Summary */}
      <div className="glass-card" style={{ marginTop: "2rem" }}>
        <h3 style={{ display: "flex", alignItems: "center", gap: "0.5rem" }}>
          <CheckCircle2 color="#10b981" /> Optimization Metrics Summary
        </h3>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(160px, 1fr))", gap: "1.5rem", marginTop: "1rem" }}>
          <div>
            <small style={{ color: "var(--text-muted)", fontSize: "0.75rem", fontWeight: "600" }}>FOG ENERGY</small>
            <h2 style={{ color: "var(--primary)" }}>{result.fog_energy} kWh</h2>
          </div>
          <div>
            <small style={{ color: "var(--text-muted)", fontSize: "0.75rem", fontWeight: "600" }}>CLOUD ENERGY</small>
            <h2 style={{ color: "var(--danger)" }}>{result.cloud_energy} kWh</h2>
          </div>
          <div>
            <small style={{ color: "var(--text-muted)", fontSize: "0.75rem", fontWeight: "600" }}>QoS SATISFACTION</small>
            <h2 style={{ color: "var(--success)" }}>{result.qos_satisfaction}%</h2>
          </div>
          <div>
            <small style={{ color: "var(--text-muted)", fontSize: "0.75rem", fontWeight: "600" }}>ENERGY SAVED</small>
            <h2 style={{ color: "var(--warning)" }}>{result.energy_saved_percent}%</h2>
          </div>
          <div>
            <small style={{ color: "var(--text-muted)", fontSize: "0.75rem", fontWeight: "600" }}>LATENCY</small>
            <h2 style={{ color: "#f43f5e" }}>{result.latency_ms} ms</h2>
          </div>
        </div>
      </div>

      {/* ── History Comparison Chart ──────────────────────────────────────── */}
      {historyChartData.length > 0 && (
        <div className="glass-card" style={{ marginTop: "2rem" }}>
          <h3 style={{ display: "flex", alignItems: "center", gap: "0.5rem", marginBottom: "0.5rem" }}>
            <History size={20} color="var(--primary)" /> Multi-Run Algorithmic Comparison (last {historyChartData.length} simulations)
          </h3>
          <p style={{ color: "var(--text-muted)", marginBottom: "1.5rem", fontSize: "0.875rem" }}>
            Real historical runs stored in the SQLite database across different scheduling algorithms.
          </p>

          <ResponsiveContainer width="100%" height={300}>
            <LineChart data={historyChartData} margin={{ top: 5, right: 20, left: 0, bottom: 5 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
              <XAxis dataKey="name" stroke="#94a3b8" tick={{ fill: "#94a3b8", fontSize: 12 }} />
              <YAxis stroke="#94a3b8" tick={{ fill: "#94a3b8", fontSize: 12 }} />
              <Tooltip
                contentStyle={{ backgroundColor: "#1e293b", border: "1px solid #475569", color: "#fff" }}
                labelStyle={{ color: "#fff" }}
              />
              <Legend wrapperStyle={{ color: "#fff" }} />
              <Line type="monotone" dataKey="QoS (%)" stroke="#6366f1" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Fog Energy" stroke="#6ceeff" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Throughput" stroke="#f59e0b" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Latency (ms)" stroke="#f43f5e" strokeWidth={2} dot={{ r: 4 }} />
            </LineChart>
          </ResponsiveContainer>

          {/* Compact history list */}
          <div style={{ marginTop: "1.5rem", overflowX: "auto" }}>
            <table style={{ width: "100%", borderCollapse: "collapse", fontSize: "0.8rem", color: "#cbd5e1" }}>
              <thead>
                <tr style={{ borderBottom: "1px solid #334155", color: "#94a3b8", textAlign: "left" }}>
                  <th style={{ padding: "8px" }}>Run</th>
                  <th style={{ padding: "8px" }}>Algorithm</th>
                  <th style={{ padding: "8px" }}>Fog Nodes</th>
                  <th style={{ padding: "8px" }}>IoT Tasks</th>
                  <th style={{ padding: "8px" }}>QoS%</th>
                  <th style={{ padding: "8px" }}>Latency (ms)</th>
                  <th style={{ padding: "8px" }}>Throughput</th>
                  <th style={{ padding: "8px" }}></th>
                </tr>
              </thead>
              <tbody>
                {[...history].reverse().map((run) => (
                  <tr key={run.id} style={{ borderBottom: "1px solid #1e293b" }}>
                    <td style={{ padding: "8px" }}>#{run.id}</td>
                    <td style={{ padding: "8px" }}>{run.algorithm}</td>
                    <td style={{ padding: "8px" }}>{run.fog_nodes}</td>
                    <td style={{ padding: "8px" }}>{run.iot_tasks}</td>
                    <td style={{ padding: "8px", color: "#4ade80" }}>{run.qos_satisfaction}%</td>
                    <td style={{ padding: "8px", color: "#f87171" }}>{run.latency_ms} ms</td>
                    <td style={{ padding: "8px" }}>{run.throughput}</td>
                    <td style={{ padding: "8px" }}>
                      <button
                        onClick={() => handleDelete(run.id)}
                        style={{ background: "none", border: "none", cursor: "pointer", color: "#ef4444" }}
                        title="Delete run"
                      >
                        <Trash2 size={15} />
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};

export default Results;