import React, { useEffect, useState } from "react";
import EnergyChart from "../charts/EnergyChart";
import LatencyChart from "../charts/LatencyChart";
import {
  Share2,
  Printer,
  CheckCircle2,
  History,
  Trash2,
} from "lucide-react";
import {
  LineChart,
  Line,
  XAxis,
  YAxis,
  Tooltip,
  Legend,
  ResponsiveContainer,
  CartesianGrid,
} from "recharts";
import { fetchHistory, deleteRun } from "../services/api";

const Results = () => {
  const [result, setResult] = useState(null);
  const [history, setHistory] = useState([]);

  useEffect(() => {
    const stored = localStorage.getItem("simulationResult");
    if (stored) {
      setResult(JSON.parse(stored));
    }
    loadHistory();
  }, []);

  const loadHistory = async () => {
    const data = await fetchHistory();
    // History comes newest-first; reverse so chart reads oldest→newest
    setHistory([...data].reverse());
  };

  const handleDelete = async (id) => {
    await deleteRun(id);
    loadHistory();
  };

  // ── Share ──────────────────────────────────────────────────────────────────
  const handleShare = async () => {
    if (!result) return;
    const text = `
🔹 Fog Resource Allocation Simulation Result

Fog Energy: ${result.fog_energy} kWh
Cloud Energy: ${result.cloud_energy} kWh
Energy Saved: ${result.energy_saved_percent}%
QoS Satisfaction: ${result.qos_satisfaction}%
Throughput: ${result.throughput}
Latency: ${result.latency_ms} ms

Generated from Fog Scheduling System`;
    try {
      if (navigator.share) {
        await navigator.share({ title: "Fog Scheduling Result", text });
      } else {
        await navigator.clipboard.writeText(text);
        alert("Result copied to clipboard!");
      }
    } catch {}
  };

  // ── Print ──────────────────────────────────────────────────────────────────
  const handlePrint = () => {
    const printContent = `
      <html>
        <head>
          <title>Fog Scheduling Report</title>
          <style>body{font-family:Arial;padding:40px} h1{color:#4f46e5} .box{margin:15px 0;font-size:18px} .highlight{font-weight:bold}</style>
        </head>
        <body>
          <h1>Fog Resource Allocation Simulation Report</h1>
          <div class="box">Fog Energy: <span class="highlight">${result.fog_energy} kWh</span></div>
          <div class="box">Cloud Energy: <span class="highlight">${result.cloud_energy} kWh</span></div>
          <div class="box">Energy Saved: <span class="highlight">${result.energy_saved_percent}%</span></div>
          <div class="box">QoS Satisfaction: <span class="highlight">${result.qos_satisfaction}%</span></div>
          <div class="box">Throughput: <span class="highlight">${result.throughput}</span></div>
          <div class="box">Latency: <span class="highlight">${result.latency_ms} ms</span></div>
          <hr/>
          <p>Generated by Fog Scheduling System</p>
        </body>
      </html>`;
    const w = window.open("", "_blank");
    w.document.write(printContent);
    w.document.close();
    w.print();
  };

  if (!result) {
    return (
      <div style={{ color: "#94a3b8", textAlign: "center", marginTop: "4rem" }}>
        No results found. Run a simulation first.
      </div>
    );
  }

  // Prepare history chart data
  const historyChartData = history.map((run, i) => ({
    name: `#${run.id}`,
    "QoS (%)": run.qos_satisfaction,
    "Fog Energy": run.fog_energy,
    Throughput: run.throughput,
    "Latency (ms)": run.latency_ms,
    algorithm: run.algorithm,
  }));

  return (
    <div className="animate-fade-in">
      {/* Header */}
      <header style={{ display: "flex", justifyContent: "space-between", marginBottom: "2rem" }}>
        <div>
          <h1>Performance Analytics</h1>
          <p style={{ color: "var(--text-muted)" }}>
            Fog node performance based on user simulation input.
          </p>
        </div>
        <div style={{ display: "flex", gap: "1rem" }}>
          <button className="btn" onClick={handleShare}>
            <Share2 size={16} /> Share
          </button>
          <button className="btn btn-primary" onClick={handlePrint}>
            <Printer size={16} /> Print
          </button>
        </div>
      </header>

      {/* Current Run Charts */}
      <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "1.5rem" }}>
        <div className="card">
          <h3>Energy Consumption</h3>
          <EnergyChart result={result} />
        </div>
        <div className="card">
          <LatencyChart result={{ ...result, iot_tasks: result.iot_tasks, fog_nodes: result.fog_nodes, algorithm: result.algorithm }} />
        </div>
      </div>

      {/* Summary */}
      <div className="glass-card" style={{ marginTop: "2rem" }}>
        <h3 style={{ display: "flex", alignItems: "center", gap: "0.5rem" }}>
          <CheckCircle2 /> Algorithm Validation Summary
        </h3>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(5,1fr)", gap: "2rem", marginTop: "1rem" }}>
          <div>
            <small>FOG ENERGY</small>
            <h2 style={{ color: "var(--primary)" }}>{result.fog_energy} kWh</h2>
          </div>
          <div>
            <small>CLOUD ENERGY</small>
            <h2 style={{ color: "var(--danger)" }}>{result.cloud_energy} kWh</h2>
          </div>
          <div>
            <small>QoS SATISFACTION</small>
            <h2 style={{ color: "var(--success)" }}>{result.qos_satisfaction}%</h2>
          </div>
          <div>
            <small>ENERGY SAVED</small>
            <h2 style={{ color: "var(--warning)" }}>{result.energy_saved_percent}%</h2>
          </div>
          <div>
            <small>LATENCY</small>
            <h2 style={{ color: "var(--primary)" }}>{result.latency_ms} ms</h2>
          </div>
        </div>
      </div>

      {/* ── History Comparison Chart ──────────────────────────────────────── */}
      {historyChartData.length > 0 && (
        <div className="glass-card" style={{ marginTop: "2rem" }}>
          <h3 style={{ display: "flex", alignItems: "center", gap: "0.5rem", marginBottom: "1.5rem" }}>
            <History size={20} /> Run Comparison (last {historyChartData.length} simulations)
          </h3>
          <p style={{ color: "var(--text-muted)", marginBottom: "1rem", fontSize: "0.875rem" }}>
            Each point = one simulation run. Change inputs on the Simulation page and run again to see the lines shift.
          </p>

          <ResponsiveContainer width="100%" height={300}>
            <LineChart data={historyChartData} margin={{ top: 5, right: 20, left: 0, bottom: 5 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
              <XAxis dataKey="name" stroke="#94a3b8" tick={{ fill: "#94a3b8", fontSize: 12 }} />
              <YAxis stroke="#94a3b8" tick={{ fill: "#94a3b8", fontSize: 12 }} />
              <Tooltip
                contentStyle={{ backgroundColor: "#1e293b", border: "1px solid #475569", color: "#fff" }}
                labelStyle={{ color: "#fff" }}
              />
              <Legend wrapperStyle={{ color: "#fff" }} />
              <Line type="monotone" dataKey="QoS (%)" stroke="#6366f1" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Fog Energy" stroke="#6ceeff" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Throughput" stroke="#f59e0b" strokeWidth={2} dot={{ r: 4 }} />
              <Line type="monotone" dataKey="Latency (ms)" stroke="#f43f5e" strokeWidth={2} dot={{ r: 4 }} />
            </LineChart>
          </ResponsiveContainer>

          {/* Compact history list */}
          <div style={{ marginTop: "1.5rem", overflowX: "auto" }}>
            <table style={{ width: "100%", borderCollapse: "collapse", fontSize: "0.8rem", color: "#cbd5e1" }}>
              <thead>
                <tr style={{ borderBottom: "1px solid #334155", color: "#94a3b8", textAlign: "left" }}>
                  <th style={{ padding: "8px" }}>Run</th>
                  <th style={{ padding: "8px" }}>Algorithm</th>
                  <th style={{ padding: "8px" }}>Fog Nodes</th>
                  <th style={{ padding: "8px" }}>IoT Tasks</th>
                  <th style={{ padding: "8px" }}>QoS%</th>
                  <th style={{ padding: "8px" }}>Latency (ms)</th>
                  <th style={{ padding: "8px" }}>Throughput</th>
                  <th style={{ padding: "8px" }}></th>
                </tr>
              </thead>
              <tbody>
                {[...history].reverse().map((run) => (
                  <tr key={run.id} style={{ borderBottom: "1px solid #1e293b" }}>
                    <td style={{ padding: "8px" }}>#{run.id}</td>
                    <td style={{ padding: "8px" }}>{run.algorithm}</td>
                    <td style={{ padding: "8px" }}>{run.fog_nodes}</td>
                    <td style={{ padding: "8px" }}>{run.iot_tasks}</td>
                    <td style={{ padding: "8px", color: "#4ade80" }}>{run.qos_satisfaction}%</td>
                    <td style={{ padding: "8px", color: "#f87171" }}>{run.latency_ms} ms</td>
                    <td style={{ padding: "8px" }}>{run.throughput}</td>
                    <td style={{ padding: "8px" }}>
                      <button
                        onClick={() => handleDelete(run.id)}
                        style={{ background: "none", border: "none", cursor: "pointer", color: "#ef4444" }}
                        title="Delete"
                      >
                        <Trash2 size={15} />
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
};

export default Results;